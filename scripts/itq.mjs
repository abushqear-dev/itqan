const ID_FAMILIES = [['FEAT-', 'features'], ['US-', 'stories'], ['AC-', 'criteria'], ['NFR-', 'NFRs'], ['SCR-', 'screens'], ['C-', 'components'], ['ADR-', 'ADRs'], ['T-', 'tasks']];
