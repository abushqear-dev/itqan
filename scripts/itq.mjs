function listFiles(root, rel, filter) {
  const out = [];
  const start = abs(root, rel);
  if (!fs.existsSync(start)) return out;
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (['node_modules', 'dist', 'build', '.git', 'coverage'].includes(entry.name)) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (!filter || filter(full)) out.push(path.relative(root, full).split(path.sep).join('/'));
    }
  };
  walk(start);
  return out;
}

