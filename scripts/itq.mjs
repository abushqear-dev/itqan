function loadState(root) {
  try { return JSON.parse(fs.readFileSync(statePath(root), 'utf8')); } catch { return null; }
}

function saveState(root, state) {
  state.updated = new Date().toISOString();
  fs.mkdirSync(abs(root, STATE_DIR), { recursive: true });
  fs.writeFileSync(statePath(root), JSON.stringify(state, null, 2) + '\n');
  fs.writeFileSync(abs(root, `${STATE_DIR}/STATUS.md`), renderStatus(state));
}

const newState = () => ({
  version: 1,
  mode: 'guided',
  inputs: [],
  inputRuling: null,
  stages: Object.fromEntries(STAGE_KEYS.map((n) => [n, { status: 'pending' }])),
});

function fail(message, code = 1) {
  process.stderr.write(message + '\n');
  process.exit(code);
}

const requireState = (root) => loadState(root) || fail('Not an Itqan project. Run init.');

function stageArg(arg) {
  if (!STAGES[arg]) fail(`Stage must be 0-6, got "${arg}".`);
  return String(arg);
}

const firstUnapproved = (state, keys) => keys.find((k) => state.stages[k].status !== 'approved');

function nextAction(state) {
  for (const n of STAGE_KEYS) {
    const status = state.stages[n].status;
    if (status !== 'approved') return `Stage ${n} (${STAGES[n].name}) is ${status}.`;
  }
  return 'All stages approved.';
}

function renderStatus(state) {
  const inputs = state.inputs.length ? state.inputs.map((i) => `${i.file} (${i.type})`).join(', ') : 'none yet';
  return [
    '# Itqan status',
    '',
    '<!-- Generated by itq.mjs. Do not edit; the source of truth is .itqan/state.json. -->',
    '',
    `Mode: ${state.mode} · Updated: ${state.updated}`,
    '',
    `Inputs: ${inputs}`,
    ...(state.inputRuling ? [`Governing source: ${state.inputRuling}`] : []),
    '',
    '| Stage | Name | Status | Location |',
    '|-------|------|--------|----------|',
    ...STAGE_KEYS.map((n) => `| ${n} | ${STAGES[n].name} | ${state.stages[n].status} | ${STAGES[n].paths.join(', ')} |`),
    '',
    `Next: ${nextAction(state)}`,
    '',
  ].join('\n');
}

// ---------- front matter ----------

function setFrontMatter(root, rel, updates) {
  const text = read(root, rel);
  if (text === null) return;
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  const fields = new Map();
  if (match) {
    for (const line of match[1].split(/\r?\n/)) {
      const kv = line.match(/^([\w-]+):\s*(.*)$/);
      if (kv) fields.set(kv[1], kv[2]);
    }
  }
  for (const [key, value] of Object.entries(updates)) {
    fields.set(key, typeof value === 'function' ? value(fields.get(key)) : value);
  }
  const header = ['---', ...[...fields].map(([k, v]) => `${k}: ${v}`), '---', ''].join('\n');
  const body = match ? text.slice(match[0].length) : text;
  fs.writeFileSync(abs(root, rel), header + body);
}

