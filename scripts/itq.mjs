    if (valuesFile) { try { supplied = JSON.parse(read(root, valuesFile) || fs.readFileSync(valuesFile, 'utf8')); } catch (e) { fail(`Cannot read values file ${valuesFile}: ${e.message}`); } }
    const values = { ...collected.values, ...supplied };
