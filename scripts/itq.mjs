// ---------- document parsing ----------

// Returns { id: blockText } for every heading whose first ID matches `prefix` (e.g. "AC-").
// A block runs until the next heading of the same or a higher level.
// How many times each ID was defined is kept on a non-enumerable `counts` property, used to report duplicates.
function headingBlocks(text, prefix) {
  const blocks = {};
  const counts = {};
  Object.defineProperty(blocks, 'counts', { value: counts });
  if (!text) return blocks;
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const heading = lines[i].match(/^(#{1,6})\s+(.*)$/);
    if (!heading) continue;
    const idMatch = heading[2].match(ID_PATTERN);
    if (!idMatch || !idMatch[0].startsWith(prefix)) continue;
    const level = heading[1].length;
    let end = i + 1;
    while (end < lines.length) {
      const next = lines[end].match(/^(#{1,6})\s/);
      if (next && next[1].length <= level) break;
      end++;
    }
    const id = idMatch[0];
    blocks[id] = (blocks[id] ? blocks[id] + '\n' : '') + lines.slice(i, end).join('\n');
    counts[id] = (counts[id] || 0) + 1;
  }
  return blocks;
}

// Text between a "## <heading>" line and the next "## " heading ('' if the section is missing).
function sectionBody(text, heading) {
  const after = (text || '').split(new RegExp(`^##\\s+${heading}`, 'mi'))[1];
  return after === undefined ? '' : after.split(/^##\s/m)[0];
}

