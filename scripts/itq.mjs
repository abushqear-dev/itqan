// ---------- document parsing ----------

// Returns { id: blockText } for every heading whose first ID matches `prefix` (e.g. "AC-").
// A block runs until the next heading of the same or a higher level.
// How many times each ID was defined is kept on a non-enumerable `counts` property, used to report duplicates.
function headingBlocks(text, prefix) {
  const blocks = {};
  const counts = {};
  Object.defineProperty(blocks, 'counts', { value: counts });
  if (!text) return blocks;
  const lines = text.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const heading = lines[i].match(/^(#{1,6})\s+(.*)$/);
    if (!heading) continue;
    const idMatch = heading[2].match(ID_PATTERN);
    if (!idMatch || !idMatch[0].startsWith(prefix)) continue;
    const level = heading[1].length;
    let end = i + 1;
    while (end < lines.length) {
      const next = lines[end].match(/^(#{1,6})\s/);
      if (next && next[1].length <= level) break;
      end++;
    }
    const id = idMatch[0];
    blocks[id] = (blocks[id] ? blocks[id] + '\n' : '') + lines.slice(i, end).join('\n');
    counts[id] = (counts[id] || 0) + 1;
  }
  return blocks;
}

const ids = (blocks) => Object.keys(blocks);
const duplicates = (blocks) => ids(blocks).filter((id) => blocks.counts[id] > 1);
const refsIn = (text) => new Set(text ? text.match(ID_PATTERN) || [] : []);

function listFiles(root, rel, filter) {
  const out = [];
  const start = abs(root, rel);
  if (!fs.existsSync(start)) return out;
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (['node_modules', 'dist', 'build', '.git', 'coverage'].includes(entry.name)) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (!filter || filter(full)) out.push(path.relative(root, full).split(path.sep).join('/'));
    }
  };
  walk(start);
  return out;
}

const TEST_FILE = /(\.test\.|\.spec\.|\/(tests?|e2e|__tests__)\/)/;
const TEXT_FILE = /\.(m?[jt]sx?|cjs|py|rb|go|rs|java|kt|cs|php|swift|feature|md)$/;
const testFiles = (root) => listFiles(root, 'app', (f) => TEST_FILE.test(f.split(path.sep).join('/')) && TEXT_FILE.test(f));
const stageFiles = (root, n) => STAGES[n].paths.flatMap((p) => (p.endsWith('/') ? listFiles(root, p.slice(0, -1)) : exists(root, p) ? [p] : []));
const readAll = (root, files) => files.map((f) => read(root, f) || '').join('\n');

// The specification's own IDs, used by several checks.
function specModel(root) {
  const spec = read(root, STAGES[1].doc);
  return {
    spec,
    feats: headingBlocks(spec, 'FEAT-'),
    stories: headingBlocks(spec, 'US-'),
    acs: headingBlocks(spec, 'AC-'),
    nfrs: headingBlocks(spec, 'NFR-'),
  };
}

// API operations with the acceptance criteria they declare via `x-acceptance: [AC-..]`.
function apiOperations(root) {
  const api = read(root, 'docs/03-tech/api.yaml');
  const ops = [];
  if (!api) return ops;
  let current = null;
  for (const line of api.split(/\r?\n/)) {
    const op = line.match(/operationId:\s*['"]?([\w.-]+)/);
    if (op) { current = { id: op[1], acs: [] }; ops.push(current); continue; }
    if (current && /x-acceptance:/.test(line)) current.acs.push(...(line.match(/AC-\d+\.\d+/g) || []));
  }
  return ops;
}

// Task progress lives in .itqan/build-log.md (the plan is locked once approved): lines like "T-002 done abc123".
function doneTasks(root) {
  const log = read(root, `${STATE_DIR}/build-log.md`) || '';
  return new Set((log.match(/^\s*[-*]?\s*(T-\d{3})\s+done\b/gim) || []).map((l) => l.match(/T-\d{3}/)[0]));
}

// Tasks in the plan with their fields.
function planTasks(root) {
  const done = doneTasks(root);
  const blocks = headingBlocks(read(root, STAGES[4].doc), 'T-');
  return ids(blocks).map((id) => {
    const block = blocks[id];
    const field = (name) => (block.match(new RegExp(`^\\s*[-*]?\\s*\\**${name}\\**:\\s*(.*)$`, 'mi')) || [])[1] || '';
    return {
      id,
      block,
      covers: field('Covers').match(/AC-\d+\.\d+/g) || [],
      stories: [...new Set((field('Covers').match(/AC-(\d+)\.\d+/g) || []).map((ac) => `US-${ac.match(/AC-(\d+)/)[1]}`))],
      depends: field('Depends').match(/T-\d{3}/g) || [],
      hasVerify: field('Verify') !== '',
      done: done.has(id),
    };
  });
}

// ---------- automated quality checks ----------

function checkStage(root, n) {
  const errors = [];
  const warnings = [];
  const doc = STAGES[n].doc;
  const files = stageFiles(root, n);
  const text = readAll(root, files);

  if (doc && !exists(root, doc)) errors.push(`${doc} does not exist.`);
  if (doc && exists(root, doc) && !/^---\r?\n[\s\S]*?\r?\n---/.test(read(root, doc))) errors.push(`${doc} has no front matter.`);
  for (const f of files) {
    if ((read(root, f) || '').includes(CLARIFY)) errors.push(`${f} still contains ${CLARIFY}] markers. Ask the user, then remove them.`);
  }

  const model = specModel(root);
  const acIds = ids(model.acs);

  if (n === '0') {
    const c = read(root, doc) || '';
    for (const section of ['Quality bar', 'Constraints', 'Boundaries']) {
      if (!new RegExp(`^##\\s+${section}`, 'mi').test(c)) errors.push(`Constitution is missing the "## ${section}" section.`);
    }
    for (const tier of ['Always', 'Ask first', 'Never']) {
      if (!new RegExp(`\\b${tier}\\b`).test(c)) errors.push(`Constitution boundaries are missing the "${tier}" tier.`);
    }
  }

  if (n === '1') {
    if (acIds.length === 0) errors.push('The Product Spec defines no acceptance criteria (headings with AC-n.m).');
    for (const section of ['Roles and permissions', 'Interpretations', 'Edge cases']) {
      if (!new RegExp(`^##\\s+${section}`, 'mi').test(model.spec || '')) errors.push(`The Product Spec is missing the "## ${section}" section.`);
    }
    const edgeSection = ((model.spec || '').split(/^##\s+Edge cases/mi)[1] || '').split(/^##\s/m)[0];
    for (const category of ['Dates and times', 'Quantities and text', 'Permissions', 'State changes', 'Multiple users', 'Notifications', 'Undo and recovery']) {
      if (edgeSection && !new RegExp(category, 'i').test(edgeSection)) errors.push(`The Edge cases section does not cover "${category}" (write AC ids or "n/a: reason").`);
    }
    for (const family of [model.feats, model.stories, model.acs, model.nfrs]) {
      for (const id of duplicates(family)) errors.push(`${id} is defined more than once.`);
    }
    for (const id of acIds) {
      const block = model.acs[id];
      if (!/\bSHALL\b/.test(block)) errors.push(`${id} is not written in EARS form (no "SHALL").`);
      if (!/Example:/i.test(block)) errors.push(`${id} has no "Example:" line.`);
      if (!model.stories[`US-${id.match(/AC-(\d+)/)[1]}`]) errors.push(`${id} belongs to US-${id.match(/AC-(\d+)/)[1]}, which is not defined.`);
    }
    for (const id of ids(model.nfrs)) {
      if (!/Measure:/i.test(model.nfrs[id])) errors.push(`${id} has no "Measure:" line.`);
      if (!/Verify:/i.test(model.nfrs[id])) errors.push(`${id} has no "Verify:" line.`);
    }
    let currentFeat = null;
    for (const line of (model.spec || '').split(/\r?\n/)) {
      const h = line.match(/^#{1,6}\s+(.*)$/);
      if (!h) continue;
      const id = (h[1].match(ID_PATTERN) || [])[0];
      if (id && id.startsWith('FEAT-')) currentFeat = id;
      if (id && id.startsWith('US-') && !currentFeat) errors.push(`${id} is not under a feature (FEAT-n) heading.`);
    }
  }

  if (n === '2') {
    const screens = headingBlocks(text, 'SCR-');
    if (ids(screens).length === 0) errors.push('The UX Spec defines no screens (headings with SCR-n).');
    for (const id of duplicates(screens)) errors.push(`${id} is defined more than once.`);
    for (const id of ids(screens)) {
      for (const state of ['Empty', 'Loading', 'Error', 'Success']) {
        if (!new RegExp(`\\b${state}\\b`, 'i').test(screens[id])) errors.push(`${id} does not describe its ${state} state.`);
      }
    }
    const referenced = refsIn(text);
    for (const id of acIds) if (!referenced.has(id)) errors.push(`${id} is not reachable from any screen or listed under "Non-UI acceptance criteria".`);
    const tokens = read(root, 'docs/02-ux/tokens.json');
    if (tokens === null) errors.push('docs/02-ux/tokens.json does not exist.');
    else {
      try { if (!tokens.includes('"$value"')) errors.push('tokens.json has no "$value" entries (W3C design tokens format).'); JSON.parse(tokens); }
      catch { errors.push('tokens.json is not valid JSON.'); }
    }
    if (!/^##\s+Design system/mi.test(text)) errors.push('The UX Spec has no "## Design system" section.');
  }

  if (n === '3') {
    const design = read(root, doc) || '';
    for (const section of ['Stack', 'Components', 'Run locally']) {
      if (!new RegExp(`^##\\s+${section}`, 'mi').test(design)) errors.push(`design.md is missing the "## ${section}" section.`);
    }
    if (/^##\s+Stack/mi.test(design) && !/\d+\.\d+/.test((design.split(/^##\s+Stack/mi)[1] || '').split(/^##\s/m)[0])) {
      errors.push('The Stack section pins no versions (e.g. "Node 24.1").');
    }
    const noApi = /No HTTP API/i.test(design);
    const api = read(root, 'docs/03-tech/api.yaml');
    if (!noApi && api === null) errors.push('docs/03-tech/api.yaml does not exist (or say "No HTTP API" in design.md).');
    if (api !== null) {
      if (!/^openapi:\s*['"]?3\./m.test(api)) errors.push('api.yaml is not an OpenAPI 3.x document.');
      const ops = apiOperations(root);
      if (ops.length === 0) errors.push('api.yaml defines no operationId.');
      for (const op of ops) if (op.acs.length === 0) errors.push(`Operation ${op.id} has no "x-acceptance" list.`);
    }
    if (!/No persistent data/i.test(design) && listFiles(root, 'docs/03-tech', (f) => /data-model\./.test(f)).length === 0) {
      errors.push('No data-model file in docs/03-tech (or say "No persistent data" in design.md).');
    }
    if (listFiles(root, 'docs/03-tech/adr', (f) => /\d{4}-.*\.md$/.test(f)).length === 0) errors.push('No ADR in docs/03-tech/adr/ (NNNN-title.md).');
    const ux = readAll(root, stageFiles(root, '2'));
    const referenced = refsIn(text);
    for (const id of ids(headingBlocks(ux, 'SCR-'))) if (!referenced.has(id)) errors.push(`${id} has no data mapping in the Technical Design ("## Screen data").`);
    for (const id of acIds) if (!referenced.has(id)) warnings.push(`${id} is not referenced in the Technical Design (fine if it is purely client-side).`);
  }

  if (n === '4') {
    const tasks = planTasks(root);
    if (tasks.length === 0) errors.push('The plan defines no tasks (headings with T-nnn).');
    const taskIds = new Set(tasks.map((t) => t.id));
    for (const t of tasks) {
      if (!t.hasVerify) errors.push(`${t.id} has no "Verify:" line.`);
      if (!/^\s*[-*]?\s*\**Covers\**:/mi.test(t.block)) errors.push(`${t.id} has no "Covers:" line.`);
      if (!/^\s*[-*]?\s*\**Depends\**:/mi.test(t.block)) errors.push(`${t.id} has no "Depends:" line.`);
      for (const d of t.depends) if (!taskIds.has(d)) errors.push(`${t.id} depends on ${d}, which does not exist.`);
      if (t.stories.length > 1) warnings.push(`${t.id} covers more than one story (${t.stories.join(', ')}); consider splitting it.`);
    }
    const first = tasks.find((t) => t.id === 'T-001');
    if (!first) errors.push('There is no T-001.');
    else if (!/skeleton/i.test(first.block)) errors.push('T-001 must be the walking skeleton (scaffold, app/CLAUDE.md, test runner, run command).');
    const visiting = new Set();
    const done = new Set();
    const byId = Object.fromEntries(tasks.map((t) => [t.id, t]));
    const visit = (id, trail) => {
      if (done.has(id) || !byId[id]) return;
      if (visiting.has(id)) { errors.push(`Dependency cycle: ${[...trail, id].join(' -> ')}.`); return; }
      visiting.add(id);
      for (const d of byId[id].depends) visit(d, [...trail, id]);
      visiting.delete(id);
      done.add(id);
    };
    for (const t of tasks) visit(t.id, []);
    const covered = new Set(tasks.flatMap((t) => t.covers));
    for (const id of acIds) if (!covered.has(id)) errors.push(`${id} is not covered by any task.`);
  }

  if (n === '5') {
    for (const t of planTasks(root)) if (!t.done) errors.push(`${t.id} is not marked done in .itqan/build-log.md.`);
    const tests = readAll(root, testFiles(root));
    if (testFiles(root).length === 0) errors.push('No test files found under app/.');
    if (!exists(root, 'app/README.md')) errors.push('app/README.md does not exist (human run instructions; see templates/app-README.md).');
    if (!exists(root, 'app/CLAUDE.md')) errors.push('app/CLAUDE.md does not exist (agent context).');
    for (const id of acIds) if (!new RegExp(`\\b${id.replace('.', '\\.')}\\b`).test(tests)) errors.push(`${id} has no test that names it.`);
  }

  if (n === '6') {
    const report = read(root, doc) || '';
    const lines = report.split(/\r?\n/);
    for (const id of acIds) {
      const line = lines.find((l) => new RegExp(`\\b${id.replace('.', '\\.')}\\b`).test(l) && /\b(PASS|FAIL)\b/.test(l));
      if (!line) { errors.push(`${id} has no PASS or FAIL line in the Acceptance Report.`); continue; }
      if (/\bPASS\b/.test(line) && !/Evidence/i.test(line)) errors.push(`${id} is PASS without "Evidence".`);
      if (/\bFAIL\b/.test(line) && !/Known gap/i.test(line)) errors.push(`${id} is FAIL without a "Known gap" note.`);
    }
    const trace = buildTrace(root);
    for (const e of trace.errors) errors.push(`Trace: ${e}`);
  }

  return { errors, warnings };
}

// ---------- traceability ----------

function buildTrace(root) {
  const errors = [];
  const warnings = [];
  const model = specModel(root);
  const uxText = readAll(root, stageFiles(root, '2'));
  const techText = readAll(root, stageFiles(root, '3'));
  const screens = headingBlocks(uxText, 'SCR-');
  const components = headingBlocks(read(root, STAGES[3].doc), 'C-');
  const adrs = new Set(listFiles(root, 'docs/03-tech/adr', (f) => /\d{4}-.*\.md$/.test(f)).map((f) => `ADR-${path.basename(f).slice(0, 4)}`));
  const tasks = planTasks(root);
  const ops = apiOperations(root);
  const tests = testFiles(root).map((f) => ({ file: f, text: read(root, f) || '' }));

  const defined = {
    'FEAT-': model.spec ? new Set(ids(model.feats)) : null,
    'US-': model.spec ? new Set(ids(model.stories)) : null,
    'AC-': model.spec ? new Set(ids(model.acs)) : null,
    'NFR-': model.spec ? new Set(ids(model.nfrs)) : null,
    'SCR-': uxText ? new Set(ids(screens)) : null,
    'C-': read(root, STAGES[3].doc) ? new Set(ids(components)) : null,
    'ADR-': exists(root, 'docs/03-tech/adr') ? adrs : null,
    'T-': read(root, STAGES[4].doc) ? new Set(tasks.map((t) => t.id)) : null,
  };
  const sources = [
    ...['docs/00-constitution.md', STAGES[1].doc, STAGES[4].doc, STAGES[6].doc].map((f) => [f, read(root, f)]),
    ['docs/02-ux', uxText],
    ['docs/03-tech', techText],
    ...tests.map((t) => [t.file, t.text]),
  ];
  for (const [file, text] of sources) {
    for (const id of refsIn(text)) {
      const prefix = Object.keys(defined).find((p) => id.startsWith(p));
      if (prefix && defined[prefix] && !defined[prefix].has(id)) errors.push(`${file} references ${id}, which is not defined.`);
    }
  }

  const rows = ids(model.acs).sort(byId).map((ac) => {
    const re = new RegExp(`\\b${ac.replace('.', '\\.')}\\b`);
    return {
      ac,
      story: `US-${ac.match(/AC-(\d+)/)[1]}`,
      screens: ids(screens).filter((s) => re.test(screens[s])),
      ops: ops.filter((o) => o.acs.includes(ac)).map((o) => o.id),
      tasks: tasks.filter((t) => t.covers.includes(ac)).map((t) => t.id),
      tests: tests.filter((t) => re.test(t.text)).map((t) => t.file),
    };
  });
  for (const r of rows) {
    if (defined['T-'] && r.tasks.length === 0) warnings.push(`${r.ac} has no task.`);
    if (tests.length && r.tests.length === 0) warnings.push(`${r.ac} has no test.`);
  }
  return { errors, warnings, rows };
}

function byId(a, b) {
  const na = a.match(/\d+/g).map(Number);
  const nb = b.match(/\d+/g).map(Number);
  return na[0] - nb[0] || (na[1] || 0) - (nb[1] || 0);
}

function writeTrace(root, trace) {
  const cell = (list) => (list.length ? list.join(', ') : '—');
  const text = [
    '# Traceability',
    '',
    '<!-- Generated by itq.mjs trace from the documents and tests. Do not edit. -->',
    '',
    '| AC | Story | Screens | API operations | Tasks | Tests |',
    '|----|-------|---------|----------------|-------|-------|',
    ...trace.rows.map((r) => `| ${r.ac} | ${r.story} | ${cell(r.screens)} | ${cell(r.ops)} | ${cell(r.tasks)} | ${cell(r.tests)} |`),
    '',
    `Errors: ${trace.errors.length} · Warnings: ${trace.warnings.length} · Generated: ${new Date().toISOString()}`,
    '',
  ].join('\n');
  fs.mkdirSync(abs(root, STATE_DIR), { recursive: true });
  fs.writeFileSync(abs(root, `${STATE_DIR}/TRACE.md`), text);
}

// ---------- commands ----------

const commands = {
  init() {
    const root = projectDir();
    for (const dir of ['docs/input', STATE_DIR]) fs.mkdirSync(abs(root, dir), { recursive: true });
    const dest = abs(root, `${STATE_DIR}/ASSUMPTIONS.md`);
    if (!fs.existsSync(dest)) fs.copyFileSync(path.join(PLUGIN_ROOT, 'templates', 'ASSUMPTIONS.md'), dest);
    const state = loadState(root) || newState();
    saveState(root, state);
    console.log(`Itqan initialised in ${root}. ${nextAction(state)}`);
  },

  // record-input <file> <brd|vision> [source]
  'record-input'(file, type, source = 'file') {
    const root = projectDir();
    const state = requireState(root);
    if (!['brd', 'vision'].includes(type)) fail('Type must be "brd" or "vision".');
    if (!file || !exists(root, file)) fail(`Input file not found: ${file}`);
    if (state.stages['1'].status === 'approved') fail('Inputs are frozen: the Product Spec is approved. Use the upstream-change process.');
    state.inputs = state.inputs.filter((i) => i.file !== file).concat({ file, type, source });
    saveState(root, state);
    console.log(`Recorded ${file} as ${type}.`);
  },

  ruling(...words) {
    const root = projectDir();
    const state = requireState(root);
    state.inputRuling = words.join(' ') || fail('Give the ruling, for example "Vision governs" or "no conflict".');
    saveState(root, state);
    console.log(`Ruling recorded: ${state.inputRuling}`);
  },

  start(arg) {
    const root = projectDir();
    const state = requireState(root);
    const n = stageArg(arg);
    const blocker = firstUnapproved(state, prerequisites(n));
    if (blocker) fail(`Cannot start stage ${n}: stage ${blocker} (${STAGES[blocker].name}) is not approved.`);
    if (n === '0' && state.inputs.length === 0) fail('Cannot start stage 0: no BRD or Vision Document recorded. Run intake first.');
    if (n === '0' && new Set(state.inputs.map((i) => i.type)).size > 1 && !state.inputRuling) fail('Cannot start stage 0: a BRD and a Vision are recorded but no ruling. Run the ruling command.');
    if (state.stages[n].status === 'approved') fail(`Stage ${n} is approved. Use reopen after the user agrees to an upstream change.`);
    state.stages[n].status = 'drafting';
    saveState(root, state);
    if (STAGES[n].doc && exists(root, STAGES[n].doc)) setFrontMatter(root, STAGES[n].doc, { status: 'draft' });
    console.log(`Stage ${n} (${STAGES[n].name}) is now drafting.`);
  },

  check(arg) {
    const root = projectDir();
    requireState(root);
    const n = stageArg(arg);
    const { errors, warnings } = checkStage(root, n);
    for (const e of errors) console.log(`ERROR   ${e}`);
    for (const w of warnings) console.log(`WARNING ${w}`);
    console.log(`Stage ${n} (${STAGES[n].name}) check: ${errors.length} error(s), ${warnings.length} warning(s).`);
    process.exit(errors.length ? 1 : 0);
  },

  approve(arg) {
    const root = projectDir();
    const state = requireState(root);
    const n = stageArg(arg);
    const required = n === '6' ? [...prerequisites(n), '5'] : prerequisites(n);
    const blocker = firstUnapproved(state, required);
    if (blocker) fail(`Cannot approve stage ${n}: stage ${blocker} (${STAGES[blocker].name}) is not approved.`);
    const { errors } = checkStage(root, n);
    if (errors.length) fail(`Cannot approve stage ${n}: the automated check found ${errors.length} error(s):\n- ${errors.join('\n- ')}`);
    state.stages[n] = { status: 'approved', approvedAt: new Date().toISOString() };
    saveState(root, state);
    if (STAGES[n].doc) setFrontMatter(root, STAGES[n].doc, { status: 'approved', approved_at: today() });
    writeTrace(root, buildTrace(root));
    console.log(`Stage ${n} (${STAGES[n].name}) approved. ${nextAction(state)}`);
  },

  // Only after the user agrees to revise an approved stage (upstream-change).
  reopen(arg) {
    const root = projectDir();
    const state = requireState(root);
    const n = stageArg(arg);
    state.stages[n].status = 'drafting';
    for (const k of STAGE_KEYS) {
      if (Number(k) > Number(n) && state.stages[k].status === 'approved') {
        state.stages[k].status = 'recheck';
        if (STAGES[k].doc && exists(root, STAGES[k].doc)) setFrontMatter(root, STAGES[k].doc, { status: 'recheck' });
      }
    }
    saveState(root, state);
    if (STAGES[n].doc && exists(root, STAGES[n].doc)) {
      setFrontMatter(root, STAGES[n].doc, { status: 'draft', version: (v) => String((parseInt(v, 10) || 1) + 1) });
    }
    console.log(`Stage ${n} reopened. Later approved stages are marked recheck.`);
  },

  trace() {
    const root = projectDir();
    requireState(root);
    const trace = buildTrace(root);
    writeTrace(root, trace);
    for (const e of trace.errors) console.log(`ERROR   ${e}`);
    for (const w of trace.warnings) console.log(`WARNING ${w}`);
    console.log(`Trace: ${trace.rows.length} acceptance criteria, ${trace.errors.length} error(s), ${trace.warnings.length} warning(s). Written to .itqan/TRACE.md.`);
    process.exit(trace.errors.length ? 1 : 0);
  },

  status() {
    const root = projectDir();
    const state = requireState(root);
    saveState(root, state);
    console.log(renderStatus(state));
  },

  // PreToolUse hook for Write|Edit|MultiEdit|NotebookEdit. Exit 2 blocks the call and shows stderr to the model.
  'hook-gate'() {
    let input = {};
    try { input = JSON.parse(fs.readFileSync(0, 'utf8')); } catch { process.exit(0); }
    const root = path.resolve(input.cwd || projectDir());
    const state = loadState(root);
    if (!state) process.exit(0);
    const target = input.tool_input?.file_path || input.tool_input?.notebook_path;
    if (!target) process.exit(0);
    const rel = path.relative(root, path.resolve(root, target)).split(path.sep).join('/');
    if (rel.startsWith('..')) process.exit(0);

    if (GENERATED.includes(rel)) fail(`Itqan: ${rel} is generated by itq.mjs. Use its commands instead of editing it.`, 2);
    if (rel.startsWith('docs/input/') && state.stages['1'].status === 'approved') {
      fail('Itqan: the inputs are frozen because the Product Spec is approved. If an input changed, stop and tell the user (upstream-change skill).', 2);
    }
    const n = STAGE_KEYS.find((k) => STAGES[k].paths.some((p) => (p.endsWith('/') ? rel.startsWith(p) : rel === p)));
    if (n === undefined) process.exit(0);
    const blocker = firstUnapproved(state, prerequisites(n));
    if (blocker) fail(`Itqan: stage ${blocker} (${STAGES[blocker].name}) is not approved, so ${rel} (stage ${n}, ${STAGES[n].name}) cannot be written yet. The order is fixed.`, 2);
    if (state.stages[n].status === 'approved') {
      fail(`Itqan: stage ${n} (${STAGES[n].name}) is approved, so ${rel} is locked. Stop, tell the user what you found, and ask whether to revise it (upstream-change skill).`, 2);
    }
    if (state.stages[n].status === 'pending') {
      fail(`Itqan: stage ${n} (${STAGES[n].name}) has not been started. Run "itq.mjs start ${n}" first.`, 2);
    }
    process.exit(0);
  },

  // SessionStart hook: stdout is added to the session context.
  'hook-session'() {
    const state = loadState(projectDir());
    if (!state) return;
    console.log(`Itqan project detected (${state.mode} mode). ${nextAction(state)} Load the itqan:start skill before doing any work on this project's documents or app.`);
  },
};

const [cmd, ...args] = process.argv.slice(2);
if (!commands[cmd]) fail(`Unknown command "${cmd}". Commands: ${Object.keys(commands).join(', ')}.`);
commands[cmd](...args);
